// Cuántas búsquedas de un rubro se disparan POR TANDA.
//
// Esto es importante: DEFAULT_CATALOG_QUERIES tiene más de 1700 entradas, y
// antes se disparaban TODAS las de un rubro apenas tocabas el chip — 538
// pedidos de una sentada para "Almacén", por ejemplo. Eso significaba tres
// problemas a la vez: la app se auto-bloqueaba con su propio rate limit
// (429), le pegaba a la API pública de Precios Claros como un scraper, y el
// rubro tardaba una eternidad en terminar de cargar.
//
// Con 12 búsquedas x 8 resultados ya entran ~96 productos reales por tanda,
// que es más de lo que alguien scrollea de una. El resto del catálogo sigue
// disponible con el botón "Ver más productos" (carga la tanda siguiente) y
// como sugerencias del buscador (lib/relatedSearches.ts).
export const CATALOG_QUERIES_PER_PAGE = 12;

// Carnes se separó de Frescos: hasta ahora todo lo que era carne, pollo,
// pescado y achuras vivía dentro de "Frescos" mezclado con fiambres, quesos,
// pastas y fruta. Las búsquedas de arriba siguen escritas con category
// 'Frescos' (son más de 500 líneas); acá se reparten por lo que dice cada
// búsqueda: lo que es carne, ave, pescado o embutido fresco pasa a 'Carnes',
// y fiambres (jamón, salame, mortadela), quesos, huevos y pastas frescas se
// quedan en Frescos. Para mover una búsqueda de rubro basta con que su texto
